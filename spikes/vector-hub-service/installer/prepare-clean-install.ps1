$payloadApp = Join-Path $PayloadRoot "app\vector_hub.py"
$payloadTs = Join-Path $PayloadRoot "app\ts2000.py"
$payloadService = Join-Path $PayloadRoot "service\vector_service.py"
$payloadPortManager = Join-Path $PayloadRoot "tools\port_manager.py"

Require-File $payloadApp "Vector Hub payload"
Require-File $payloadTs "TS-2000 adapter payload"
Require-File $payloadService "Windows service payload"
Require-File $payloadPortManager "Port Manager payload"
Require-File $PythonExe "Private Python runtime"

$com0com = Find-Com0comSetup
if (-not $com0com) { throw "com0com setupc.exe was not found. Run ensure-runtime.ps1 first." }

Write-Host ""
Write-Host "GADX Vector - Phase D5 clean-install preparation" -ForegroundColor Cyan
Write-Host "Install root : $InstallRoot"
Write-Host "Python       : $PythonExe"
Write-Host "com0com      : $com0com"
Write-Host "vector.ini   : $(if (Test-Path $VectorIni) { 'existing - will be preserved' } else { 'will be created using free COM101+ ports' })"
Write-Host "Port Manager : $payloadPortManager"
Write-Host ""

if (-not $Apply) {
    Write-Host "PREVIEW ONLY - no changes were made." -ForegroundColor Yellow
    Write-Host "  1. Deploy current app/service/tools payload."
    Write-Host "  2. Create initial vector.ini only if it does not exist, allocating free internal COMs from COM101 upward."
    Write-Host "  3. Open Port Manager and wait for the operator to review/apply COM pairs."
    Write-Host "  4. Detect whether com0com pairs changed and mark reboot pending when needed."
    Write-Host "  5. Preserve existing vector.ini and existing COM pairs whenever present."
    exit 0
}

foreach ($dir in @("app","service","tools","config","logs")) {
    New-Item -ItemType Directory -Force -Path (Join-Path $InstallRoot $dir) | Out-Null
}

Write-Host "Deploying current payload..."
Copy-Item -Force $payloadApp (Join-Path $InstallRoot "app\vector_hub.py")
Copy-Item -Force $payloadTs (Join-Path $InstallRoot "app\ts2000.py")
Copy-Item -Force $payloadService (Join-Path $InstallRoot "service\vector_service.py")
Copy-Item -Force $payloadPortManager $PortManager

if (-not (Test-Path $VectorIni -PathType Leaf)) {
    $internalPorts = Get-FreeVectorPorts $com0com 4
    Write-Host "Creating initial vector.ini with internal ports: COM$($internalPorts[0]), COM$($internalPorts[1]), COM$($internalPorts[2]), COM$($internalPorts[3])"
    [void](Write-InitialVectorIni $internalPorts)
} else {
    Write-Host "Existing vector.ini found; preserving it."
}

$before = Get-Com0comSnapshot $com0com

Write-Host ""
Write-Host "Opening GADX Vector Port Manager." -ForegroundColor Yellow
Write-Host "Review the suggested clients and COM pairs, click 'Aplicar configuracao' if correct, then close the window."
$p = Start-Process -FilePath $PythonExe -ArgumentList @($PortManager) -Wait -PassThru
