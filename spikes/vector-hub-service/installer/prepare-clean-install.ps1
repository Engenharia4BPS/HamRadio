$PayloadRoot = Join-Path $InstallerRoot "payload"
$PythonExe = Join-Path $InstallRoot "runtime\python.exe"
$VectorIni = Join-Path $InstallRoot "config\vector.ini"
$PortManager = Join-Path $InstallRoot "tools\port_manager.py"
$RebootMarker = Join-Path $InstallRoot "config\reboot-pending.flag"

function Assert-Administrator {
    $identity = [Security.Principal.WindowsIdentity]::GetCurrent()
    $principal = New-Object Security.Principal.WindowsPrincipal($identity)
    if (-not $principal.IsInRole([Security.Principal.WindowsBuiltInRole]::Administrator)) {
        throw "Run this script from an elevated PowerShell prompt."
    }
}

function Require-File([string]$Path,[string]$Label) {
    if (-not (Test-Path $Path -PathType Leaf)) { throw "$Label is missing: $Path" }
}

function Find-Com0comSetup {
    foreach ($candidate in @(
        "C:\Ham\com0com\setupc.exe",
        "$env:ProgramFiles\com0com\setupc.exe",
        "${env:ProgramFiles(x86)}\com0com\setupc.exe"
    )) {
        if ($candidate -and (Test-Path $candidate -PathType Leaf)) { return (Resolve-Path $candidate).Path }
    }
    return $null
}

function Invoke-Com0com([string]$SetupExe,[string[]]$Arguments) {
    $cwd = Split-Path -Parent $SetupExe
    Push-Location $cwd
    try { return @(& $SetupExe @Arguments 2>&1) }
    finally { Pop-Location }
}

function Get-Com0comSnapshot([string]$SetupExe) {
    if (-not $SetupExe) { return "" }
    $output = Invoke-Com0com $SetupExe @('list')
    return (($output | ForEach-Object { [string]$_ }) -join "`n")
}

function Get-BusyComNumbers([string]$SetupExe) {
    $busy = New-Object 'System.Collections.Generic.HashSet[int]'
    try {
        $output = Invoke-Com0com $SetupExe @('busynames','COM?*')
        foreach ($line in $output) {
            if ([string]$line -match '^\s*COM(\d+)\s*$') { [void]$busy.Add([int]$Matches[1]) }
        }
    } catch { }

    try {
        foreach ($p in [System.IO.Ports.SerialPort]::GetPortNames()) {
            if ($p -match '^COM(\d+)$') { [void]$busy.Add([int]$Matches[1]) }
        }
    } catch { }
    return $busy
}

function Get-FreeVectorPorts([string]$SetupExe,[int]$Count = 4) {
    $busy = Get-BusyComNumbers $SetupExe
    $ports = @()
    for ($n=101; $n -le 199 -and $ports.Count -lt $Count; $n++) {
        if (-not $busy.Contains($n)) { $ports += $n }
    }
    if ($ports.Count -lt $Count) { throw "Unable to find $Count free Vector COM ports between COM101 and COM199." }
    return $ports
}

function Write-InitialVectorIni([int[]]$InternalPorts) {
    $cat1 = $InternalPorts[0]
    $key1 = $InternalPorts[1]
    $cat2 = $InternalPorts[2]
    $key2 = $InternalPorts[3]
    $text = @"
; GADX Vector Hub
; Initial configuration generated by clean installer.
; Review virtual COM pairs in GADX Vector Port Manager before starting the service.

[cat]
ports = COM$cat1, COM$cat2
baud = 19200

[keying]
; clientN = NOME,PORTA_VECTOR,PTT_INPUT,CW_INPUT
client1 = Log4OM,COM$key1,DTR,RTS
client2 = N1MM,COM$key2,DTR,NONE

[radio_keying]
; Adjust these values for the physical radio/interface before starting GADXVectorHub.
port = COM4
baud = 19200
ptt_line = RTS
cw_line = DTR

[rig]
host = 127.0.0.1
port = 4532
poll_ms = 250

[runtime]
allow_write = true
allow_ptt = true
allow_cw = true

[service]
startup = delayed-auto
recovery = restart

[logging]
level = INFO
max_mb = 5
backups = 5

[ports]
application_start = 15
vector_start = 101
"@
    $encoding = New-Object System.Text.UTF8Encoding($false)
    [System.IO.File]::WriteAllText($VectorIni,$text,$encoding)
    return @($cat1,$key1,$cat2,$key2)
}

